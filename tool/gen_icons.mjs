// Generates lib/widgets/core/ui_icon_paths.dart from assets/icons/*.svg.
// Run from the repo root: node tool/gen_icons.mjs
//
// Icons are 24-grid strokes (width 1.8, round caps and joins). Elements with
// fill="#000" (or a filled root) are filled as well as stroked. Supported:
// <path> with M L H V C A Z (absolute and relative), <circle>, <rect rx>.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const SRC = "assets/icons";
const OUT = "lib/widgets/core/ui_icon_paths.dart";

const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const n = (v) => {
  const r = Math.round(v * 1000) / 1000;
  return Object.is(r, -0) ? "0" : String(r);
};
const attr = (tag, name) => {
  const m = tag.match(new RegExp(`[ ]${name}="([^"]*)"`));
  return m ? m[1] : null;
};

/** SVG path data -> Dart Path cascade calls. */
function pathOps(d) {
  const ops = [];
  let i = 0;
  let x = 0, y = 0, sx = 0, sy = 0, cmd = "";
  const ws = () => { while (i < d.length && /[\s,]/.test(d[i])) i++; };
  const num = () => {
    ws();
    const m = d.slice(i).match(/^[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?/);
    if (!m) throw new Error(`number expected at ${i} in "${d}"`);
    i += m[0].length;
    return parseFloat(m[0]);
  };
  const flag = () => { ws(); const c = d[i++]; if (c !== "0" && c !== "1") throw new Error(`flag expected in "${d}"`); return c === "1"; };
  const more = () => { ws(); return i < d.length && /[-+.\d]/.test(d[i]); };

  while (true) {
    ws();
    if (i >= d.length) break;
    if (/[a-zA-Z]/.test(d[i])) cmd = d[i++];
    const rel = cmd === cmd.toLowerCase();
    switch (cmd.toUpperCase()) {
      case "M": {
        const px = num(), py = num();
        x = rel ? x + px : px; y = rel ? y + py : py; sx = x; sy = y;
        ops.push(`..moveTo(${n(x)}, ${n(y)})`);
        cmd = rel ? "l" : "L"; // further pairs are implicit line-tos
        break;
      }
      case "L": {
        const px = num(), py = num();
        x = rel ? x + px : px; y = rel ? y + py : py;
        ops.push(`..lineTo(${n(x)}, ${n(y)})`);
        break;
      }
      case "H": { const v = num(); x = rel ? x + v : v; ops.push(`..lineTo(${n(x)}, ${n(y)})`); break; }
      case "V": { const v = num(); y = rel ? y + v : v; ops.push(`..lineTo(${n(x)}, ${n(y)})`); break; }
      case "C": {
        const p = [num(), num(), num(), num(), num(), num()].map((v, k) => (rel ? v + (k % 2 ? y : x) : v));
        ops.push(`..cubicTo(${p.map(n).join(", ")})`);
        x = p[4]; y = p[5];
        break;
      }
      case "A": {
        const rx = num(), ry = num(), rot = num();
        const large = flag(), sweep = flag();
        const px = num(), py = num();
        x = rel ? x + px : px; y = rel ? y + py : py;
        const radius = rx === ry ? `Radius.circular(${n(rx)})` : `Radius.elliptical(${n(rx)}, ${n(ry)})`;
        ops.push(`..arcToPoint(const Offset(${n(x)}, ${n(y)}), radius: const ${radius}, rotation: ${n(rot)}, largeArc: ${large}, clockwise: ${sweep})`);
        break;
      }
      case "Z": ops.push("..close()"); x = sx; y = sy; break;
      default: throw new Error(`unsupported command ${cmd} in "${d}"`);
    }
    if (cmd.toUpperCase() !== "Z" && !more()) cmd = "";
  }
  return ops;
}

function shapeOps(tag) {
  if (tag.startsWith("<path")) return pathOps(attr(tag, "d"));
  if (tag.startsWith("<circle")) {
    const cx = +attr(tag, "cx"), cy = +attr(tag, "cy"), r = +attr(tag, "r");
    return [`..addOval(const Rect.fromLTRB(${n(cx - r)}, ${n(cy - r)}, ${n(cx + r)}, ${n(cy + r)}))`];
  }
  if (tag.startsWith("<rect")) {
    const x = +attr(tag, "x"), y = +attr(tag, "y"), w = +attr(tag, "width"), h = +attr(tag, "height");
    const rx = +(attr(tag, "rx") ?? 0);
    const rect = `const Rect.fromLTWH(${n(x)}, ${n(y)}, ${n(w)}, ${n(h)})`;
    return [rx > 0 ? `..addRRect(RRect.fromRectAndRadius(${rect}, const Radius.circular(${n(rx)})))` : `..addRect(${rect})`];
  }
  throw new Error(`unsupported element ${tag}`);
}

const files = readdirSync(SRC).filter((f) => f.endsWith(".svg")).sort();
const entries = [];
for (const f of files) {
  const svg = readFileSync(`${SRC}/${f}`, "utf8");
  const root = svg.match(/<svg[^>]*>/)[0];
  const rootFilled = attr(root, "fill") !== "none";
  const stroke = [], fill = [];
  for (const tag of svg.match(/<(path|circle|rect)\s[^>]*>/g) ?? []) {
    const ops = shapeOps(tag);
    stroke.push(...ops);
    const own = attr(tag, "fill");
    if (own ? own !== "none" : rootFilled) fill.push(...ops);
  }
  const path = (ops) => (ops.length ? `Path()\n      ${ops.join("\n      ")}` : "null");
  entries.push(`  Ui.${camel(f.replace(".svg", ""))}: (\n    stroke: ${path(stroke)},\n    fill: ${path(fill)},\n  ),`);
}

writeFileSync(OUT, `// GENERATED by tool/gen_icons.mjs from assets/icons/*.svg — do not edit.
import 'dart:ui';

import 'ui_icon.dart';

/// Icon geometry on the 24×24 grid: [stroke] is drawn at width 1.8 with round
/// caps and joins; [fill], when present, is filled as well.
typedef UiIconShape = ({Path stroke, Path? fill});

final Map<Ui, UiIconShape> kUiIconShapes = <Ui, UiIconShape>{
${entries.join("\n")}
};
`);
console.log(`${files.length} icons -> ${OUT}`);
